FontClass::FontClass()
{
    width = 64;
    height = 128;
    data = NULL;
}
FontClass::FontClass(std::uint8_t p_width, std::uint8_t p_height, const std::uint8_t fontArray[FontClass::MAX_CHARS])
{
    width = p_width;
    height = p_height;
    data = fontArray;
}
FontClass::FontClass(std::uint8_t p_width, std::uint8_t p_height, const std::uint8_t fontArray[FontClass::MAX_CHARS],
		     std::uint16_t p_dataLength)
{
    width = p_width;
    height = p_height;
    data = fontArray;
    dataLength = p_dataLength;
}

std::uint16_t FontClass::getCharIndex(char ch)
{
    // get index of character into stored font array.
    // NB: using latin basic unicode set *FROM* the space char to DEL(replaced with '°').
    std::uint16_t fontIndex;

    // check for control chars
    if(ch == '\n')
    {
	fontIndex = dataLength-1;
    }
    else if( ch >= 0x20 && ch < 0x7F)
    {
	// get offset into font array (i.e. staring from unicode space)
	fontIndex = ch - 0x20;
    }
    // if unicode '°' replace with DEL.
    else if(ch == 0xF8)
    {
	fontIndex = 0x7F;
    }
    // else not in range.
    else
    {
	fontIndex = 0xFF;
    }

    return fontIndex;
}

std::vector<std::uint8_t> FontClass::getChar(std::uint16_t fontIndex)
{
    // The actual character location in array.
    std::uint16_t fontOffset = fontIndex * width;

    std::uint8_t arr[width];
    std::memcpy(&arr, &data[fontOffset], width);
    return {arr, arr + sizeof(arr) / sizeof(arr[0])};

}


